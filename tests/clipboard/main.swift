import AppKit
func check(_ value: @autoclosure () -> Bool, _ message: String) { if !value() { fatalError(message) } }
let board = NSPasteboard(name: NSPasteboard.Name("bucky-test-" + UUID().uuidString))
defer { board.releaseGlobally() }
let delivery = ClipboardDelivery(pasteboard: board)
func original() {
    board.clearContents()
    let first = NSPasteboardItem(); first.setString("Previous", forType: .string); first.setData(Data([1, 2, 3]), forType: .rtf)
    let second = NSPasteboardItem(); second.setString("Second", forType: .string)
    check(board.writeObjects([first, second]), "Fixture clipboard")
}
original()
check(delivery.stagePaste("Dictation", preserve: true), "Stage dictation")
check(board.string(forType: .string) == "Dictation", "Staged value")
check(delivery.restorePending(), "Restore snapshot")
check(board.pasteboardItems?.count == 2, "All items restored")
check(board.pasteboardItems?.first?.data(forType: .rtf) == Data([1, 2, 3]), "Rich format restored")
check(board.string(forType: .string) == "Previous\nSecond", "Previous text restored")
original(); delivery.stagePaste("First dictation", preserve: true); delivery.stagePaste("Second dictation", preserve: true)
check(delivery.restorePending() && board.string(forType: .string) == "Previous\nSecond", "Repeated pastes preserve original clipboard")
original(); delivery.stagePaste("Dictation", preserve: true)
board.clearContents(); board.setString("User's new copy", forType: .string)
check(!delivery.restorePending() && board.string(forType: .string) == "User's new copy", "Never replace a new user copy")
original(); delivery.stagePaste("Dictation", preserve: true); delivery.copy("Explicit copy")
check(!delivery.restorePending() && board.string(forType: .string) == "Explicit copy", "Explicit Copy is persistent")
board.clearContents(); delivery.stagePaste("Dictation", preserve: true)
check(delivery.restorePending() && (board.pasteboardItems ?? []).isEmpty, "Originally empty clipboard restored")
original(); delivery.stagePaste("Dictation", preserve: false)
check(!delivery.restorationPending && board.string(forType: .string) == "Dictation", "Opt out")
original(); let limited = ClipboardDelivery(pasteboard: board, maxBytes: 1)
check(limited.stagePaste("Dictation", preserve: true) && !limited.restorationPending, "Large clipboard avoids partial restoration")
check(ClipboardDelivery.holdDuration(for: "com.microsoft.Word") == 3, "Slow-reading app hold")
check(ClipboardDelivery.holdDuration(for: "com.example.remote") == 5, "Remote app hold")
original(); delivery.stagePaste("Timed paste", preserve: true); delivery.scheduleRestore(after: 0.01)
RunLoop.main.run(until: Date().addingTimeInterval(0.05))
check(board.string(forType: .string) == "Previous\nSecond", "Scheduled restoration runs")
print("Clipboard checks passed: rich multi-item restore, empty clipboard, repeated pastes, new-copy race, explicit Copy, bounds and hold times")
